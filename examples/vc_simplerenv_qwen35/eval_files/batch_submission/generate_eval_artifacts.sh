#!/bin/bash
# generate_eval_artifacts.sh
# Generate SimplerEnv evaluation run_eval.sh into training output_dir.
# Mirrors vc_Robotwin2_qwen35/eval_files/batch_submission/generate_eval_artifacts.sh.
#
# Usage: generate_eval_artifacts.sh <repo_root> <output_dir> <run_id> <action_mode> <normalization_mode>

set -e

if [[ $# -ne 5 ]]; then
    echo "Usage: generate_eval_artifacts.sh <repo_root> <output_dir> <run_id> <action_mode> <normalization_mode>"
    exit 1
fi

REPO_ROOT="$1"
OUTPUT_DIR="$2"
RUN_ID="$3"
ACTION_MODE="$4"
NORMALIZATION_MODE="$5"

batch_submit_script="${REPO_ROOT}/examples/vc_simplerenv_qwen35/eval_files/batch_submission/submit_multi_tasks.sh"
run_eval_sh="${OUTPUT_DIR}/run_eval.sh"

if [[ ! -f "${batch_submit_script}" ]]; then
    echo "ERROR: submit script not found: ${batch_submit_script}"
    exit 1
fi

cat > "${run_eval_sh}" <<EOF
#!/bin/bash
set -e

# Auto-generated by ${0}
# Run from packages/starVLA to submit all SimplerEnv tasks as sbatch jobs.
# Edit TASK_LIST in submit_multi_tasks.sh as needed.
#
# Usage:
#   bash ${run_eval_sh}
#   CKPT_PATH=/path/to/pytorch_model.pt bash ${run_eval_sh}

CKPT_PATH=\${CKPT_PATH:-${OUTPUT_DIR}/final_model/pytorch_model.pt}
PORT=\${PORT:-6780}
OBJ_EPISODE_START=\${OBJ_EPISODE_START:-0}
OBJ_EPISODE_END=\${OBJ_EPISODE_END:-24}
PREFLIGHT_SIM=\${PREFLIGHT_SIM:-0}
# EXP_NAME defaults to run_id; override to tag intermediate-checkpoint evals.
EXP_NAME=\${EXP_NAME:-${RUN_ID}}
DATASET_NAME=\${DATASET_NAME:-bridge_rt_1}

STAR_VLA_PYTHON=\${STAR_VLA_PYTHON:-/shared/home/ZWA0839/.conda/envs/starVLA/bin/python}
SIM_PYTHON=\${SIM_PYTHON:-/shared/home/ZWA0839/.conda/envs/simpler_env/bin/python}
SIMPLERENV_PATH=\${SIMPLERENV_PATH:-/shared/home/ZWA0839/Projects/VisualContextVLA/packages/SimplerEnv}

export CKPT_PATH PORT OBJ_EPISODE_START OBJ_EPISODE_END PREFLIGHT_SIM
export EXP_NAME DATASET_NAME
export STAR_VLA_PYTHON SIM_PYTHON SIMPLERENV_PATH

bash "${batch_submit_script}"

echo ""
echo "All task jobs submitted. Check status with: squeue -u \$USER"
echo "Logs will appear in: \$(dirname "\${CKPT_PATH}")/output_eval/"
EOF

chmod +x "${run_eval_sh}"

echo "Generated: ${run_eval_sh}"
