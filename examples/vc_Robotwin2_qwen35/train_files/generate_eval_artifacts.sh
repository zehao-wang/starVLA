#!/bin/bash
# generate_eval_artifacts.sh
# Shared helper for training scripts to generate:
#   1) output_dir/deploy_policy.yml
#   2) output_dir/run_eval.sh

set -e

if [[ $# -ne 5 ]]; then
    echo "Usage: generate_eval_artifacts.sh <repo_root> <output_dir> <run_id> <action_mode> <normalization_mode>"
    exit 1
fi

REPO_ROOT="$1"
OUTPUT_DIR="$2"
RUN_ID="$3"
ACTION_MODE="$4"
NORMALIZATION_MODE="$5"

eval_files_dir="${REPO_ROOT}/examples/vc_Robotwin2_qwen35/eval_files"
batch_submit_script="${eval_files_dir}/batch_submission/submit_multi_tasks.sh"
deploy_template="${eval_files_dir}/deploy_policy.yml"
deploy_out="${OUTPUT_DIR}/deploy_policy.yml"
run_eval_sh="${OUTPUT_DIR}/run_eval.sh"

if [[ ! -f "${deploy_template}" ]]; then
    echo "ERROR: deploy template not found: ${deploy_template}"
    exit 1
fi

if [[ ! -f "${batch_submit_script}" ]]; then
    echo "ERROR: submit script not found: ${batch_submit_script}"
    exit 1
fi

cp "${deploy_template}" "${deploy_out}"

python3 - <<PY
import yaml
from pathlib import Path

deploy_path = Path("${deploy_out}")
run_id = "${RUN_ID}"
policy_path = Path("${OUTPUT_DIR}") / "final_model" / "pytorch_model.pt"
action_mode = "${ACTION_MODE}"
normalization_mode = "${NORMALIZATION_MODE}"

with deploy_path.open("r", encoding="utf-8") as f:
    cfg = yaml.safe_load(f) or {}

cfg["exp_name"] = run_id
cfg["policy_ckpt_path"] = str(policy_path)
cfg["action_mode"] = action_mode
cfg["normalization_mode"] = normalization_mode

with deploy_path.open("w", encoding="utf-8") as f:
    yaml.safe_dump(cfg, f, sort_keys=False, allow_unicode=False)
PY

cat > "${run_eval_sh}" <<EOF
#!/bin/bash
set -e

# Auto-generated by ${0}
# Edit TASK_LIST in submit_multi_tasks.sh as needed.

HF_DATASET_NAME=\${HF_DATASET_NAME:-lerobot_robotwin_rand20k_debug}
MAX_EPISODES=\${MAX_EPISODES:-none}
GPU_ID=\${GPU_ID:-0}
PORT=\${PORT:-5694}
SPLIT=\${SPLIT:-Randomized}

DEPLOY_POLICY_YML=\${DEPLOY_POLICY_YML:-${deploy_out}}
HF_LEROBOT_HOME=\${HF_LEROBOT_HOME:-/shared/home/ZWA0839/Projects/VisualContextVLA/data/robotwin2/hf_lerobot}
ROBOTWIN_CONDA_ENV=\${ROBOTWIN_CONDA_ENV:-RoboTwin}
STAR_VLA_PYTHON=\${STAR_VLA_PYTHON:-/shared/home/ZWA0839/.conda/envs/starVLA/bin/python}
ROBOTWIN_PATH=\${ROBOTWIN_PATH:-${REPO_ROOT}/../RoboTwin}

export HF_DATASET_NAME MAX_EPISODES GPU_ID PORT SPLIT
export DEPLOY_POLICY_YML HF_LEROBOT_HOME ROBOTWIN_CONDA_ENV STAR_VLA_PYTHON ROBOTWIN_PATH

bash "${batch_submit_script}"
EOF

chmod +x "${run_eval_sh}"

echo "Generated: ${deploy_out}"
echo "Generated: ${run_eval_sh}"
